import { copyFileSync, existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { extname, join } from 'node:path';
import { TEMPLATES_DIR, UserError, ensureDir, gsapFile, hyperframes, round } from './util.js';
import { readPrep, timeline } from './project.js';
import { groupWords, parseSubtitles, remapCues } from './captions.js';
import { probe } from './ffmpeg.js';

const esc = (s) =>
  String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

const r = (n) => round(n, 3);

/**
 * One graphic as a HyperFrames sub-composition file. Its timeline runs in
 * local time: 0 is the moment the graphic appears on the main timeline.
 */
function subComposition({ id, width, height, duration, body, animation }) {
  return `<!-- Generated by vedit; overwritten by \`node vedit.js build\`. -->
<template id="${id}-template">
  <div data-composition-id="${id}" data-width="${width}" data-height="${height}" data-duration="${r(duration)}">
${body}
    <script>
      (function () {
        const tl = gsap.timeline({ paused: true });
        ${animation.join('\n        ')}
        window.__timelines = window.__timelines || {};
        window.__timelines["${id}"] = tl;
      })();
    </script>
  </div>
</template>
`;
}

/**
 * Build the HyperFrames project files: index.html (footage, audio, and where
 * each graphic sits) plus one sub-composition file per graphic in compositions/.
 * Pure function: everything it needs is passed in, so it is easy to test.
 * Returns { "index.html": "...", "compositions/intro.html": "...", ... }.
 */
export function compositionFiles({ project, tl, captions = [], logo = null, musicFile = null, musicDuration = Infinity }) {
  const { width, height, fps } = project.format;
  const files = {};
  const layers = [];
  // Graphics live in compositions/, so assets in the build folder are one level up.
  const logoTag = logo ? `<img class="logo" src="../${esc(logo)}" alt="" />` : '';
  const mount = (id, start, duration, track, extra = '') =>
    layers.push(`
      <div id="${id}-layer" class="layer"${extra} data-composition-id="${id}" data-composition-src="compositions/${id}.html" data-start="${r(start)}" data-duration="${r(duration)}" data-track-index="${track}"></div>`);

  if (tl.introDuration > 0) {
    const d = tl.introDuration;
    files['compositions/intro.html'] = subComposition({
      id: 'intro', width, height, duration: d,
      body: `    <div class="card">
      ${logoTag}
      <h1>${esc(project.title)}</h1>
      ${project.subtitle ? `<p>${esc(project.subtitle)}</p>` : ''}
      <div class="bar"></div>
    </div>`,
      animation: [
        `tl.fromTo('[data-composition-id="intro"] h1', { opacity: 0, y: 40 }, { opacity: 1, y: 0, duration: 0.7, ease: "power3.out" }, 0.2);`,
        `tl.fromTo('[data-composition-id="intro"] p, [data-composition-id="intro"] .logo', { opacity: 0, y: 24 }, { opacity: 1, y: 0, duration: 0.6, ease: "power3.out" }, 0.4);`,
        `tl.fromTo('[data-composition-id="intro"] .bar', { scaleX: 0 }, { scaleX: 1, duration: 0.6, ease: "power2.inOut" }, 0.5);`,
        `tl.to('[data-composition-id="intro"] .card', { opacity: 0, duration: 0.4, ease: "power1.in" }, ${r(Math.max(0, d - 0.4))});`,
      ],
    });
    mount('intro', 0, d, 1);
  }

  const lt = project.lowerThird;
  if (lt?.enabled && lt.name) {
    const start = tl.mainStart + Number(lt.at ?? 1);
    const d = Math.min(Number(lt.duration ?? 5), Math.max(0, tl.outroStart - start));
    if (d > 1) {
      files['compositions/lower-third.html'] = subComposition({
        id: 'lower-third', width, height, duration: d,
        body: `    <div class="lower-third">
      <div class="accent"></div>
      <div class="text">
        <div class="name">${esc(lt.name)}</div>
        ${lt.role ? `<div class="role">${esc(lt.role)}</div>` : ''}
      </div>
    </div>`,
        animation: [
          `tl.fromTo('[data-composition-id="lower-third"] .lower-third', { x: -80, opacity: 0 }, { x: 0, opacity: 1, duration: 0.5, ease: "power3.out" }, 0);`,
          `tl.to('[data-composition-id="lower-third"] .lower-third', { x: -40, opacity: 0, duration: 0.4, ease: "power2.in" }, ${r(d - 0.4)});`,
        ],
      });
      mount('lower-third', start, d, 2);
    }
  }

  const lines = captions
    .map((c) => ({ ...c, end: Math.min(c.end, tl.mainDuration) }))
    .filter((c) => c.end - c.start > 0.05);
  if (lines.length) {
    files['compositions/captions.html'] = subComposition({
      id: 'captions', width, height, duration: tl.mainDuration,
      body: lines.map((c, i) => `    <div class="caption" id="cap-${i}">${esc(c.text)}</div>`).join('\n'),
      animation: lines.flatMap((c, i) => [
        `tl.set("#cap-${i}", { autoAlpha: 1 }, ${r(c.start)});`,
        `tl.set("#cap-${i}", { autoAlpha: 0 }, ${r(c.end)});`,
      ]),
    });
    mount('captions', tl.mainStart, tl.mainDuration, 3, ' data-track-kind="captions"');
  }

  if (tl.outroDuration > 0) {
    const o = project.outro;
    files['compositions/outro.html'] = subComposition({
      id: 'outro', width, height, duration: tl.outroDuration,
      body: `    <div class="card">
      ${logoTag}
      <h1>${esc(o.text)}</h1>
      ${o.cta ? `<div class="cta">${esc(o.cta)}</div>` : ''}
    </div>`,
      animation: [
        `tl.fromTo('[data-composition-id="outro"] .card', { opacity: 0 }, { opacity: 1, duration: 0.5 }, 0);`,
        `tl.fromTo('[data-composition-id="outro"] h1', { opacity: 0, y: 30 }, { opacity: 1, y: 0, duration: 0.6, ease: "power3.out" }, 0.2);`,
        `tl.fromTo('[data-composition-id="outro"] .cta', { opacity: 0, scale: 0.85 }, { opacity: 1, scale: 1, duration: 0.5, ease: "back.out(2)" }, 0.6);`,
      ],
    });
    mount('outro', tl.outroStart, tl.outroDuration, 1);
  }

  // Audio here is only for previewing in HyperFrames Studio. The exported
  // soundtrack (ducking, effects, loudness) is mixed by FFmpeg in `render`.
  const audio = [
    `
      <audio id="voice" data-start="${r(tl.mainStart)}" data-duration="${r(tl.mainDuration)}" data-track-index="4" src="voice.wav"></audio>`,
  ];
  if (musicFile) {
    // The final mix loops short tracks; the preview just plays the track once.
    audio.push(`
      <audio id="music" data-start="0" data-duration="${r(Math.min(tl.total, musicDuration))}" data-track-index="5" data-volume="0.25" data-fade-in="1" data-fade-out="3" src="${esc(musicFile)}"></audio>`);
  }

  files['index.html'] = `<!doctype html>
<!-- Generated by vedit from projects/${esc(project.name)}/project.json. Edits here are overwritten by \`node vedit.js build\`. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=${width}, height=${height}" />
    <script src="gsap.min.js"></script>
    <link rel="stylesheet" href="theme.css" />
    <style>
      html, body { width: ${width}px; height: ${height}px; }
      :root { --accent: ${esc(project.brand?.accent || '#ff5a36')}; }
    </style>
  </head>
  <body>
    <div id="root" class="${lines.length ? 'has-captions' : ''}" data-composition-id="main" data-start="0" data-duration="${r(tl.total)}" data-fps="${fps}" data-width="${width}" data-height="${height}">
      <video id="main-video" class="clip" data-start="${r(tl.mainStart)}" data-duration="${r(tl.mainDuration)}" data-track-index="0" src="main.mp4" muted playsinline></video>${layers.join('')}${audio.join('')}
      <script>
        const tl = gsap.timeline({ paused: true });
        window.__timelines = window.__timelines || {};
        window.__timelines["main"] = tl;
      </script>
    </div>
  </body>
</html>
`;
  return files;
}

/** Captions for the edited footage, in footage time (0 = first kept frame). */
export async function loadCaptions({ project, paths, prep, onStatus = () => {} }) {
  const cfg = project.captions;
  if (!cfg?.enabled) return [];

  if (cfg.file) {
    const file = join(paths.dir, cfg.file);
    if (!existsSync(file)) throw new UserError(`Caption file not found: ${file}`);
    const cues = parseSubtitles(readFileSync(file, 'utf8'));
    // Subtitles made from the original recording need shifting to match the cuts.
    return cfg.timing === 'edited' ? cues : remapCues(cues, prep.segments);
  }

  // No file given: transcribe the cleaned-up voice with HyperFrames (whisper / parakeet).
  if (!existsSync(paths.transcript) || cfg.refresh) {
    onStatus('Transcribing voice for captions (first run downloads a speech model)…');
    await hyperframes(['transcribe', paths.voice, '--dir', paths.build, ...(cfg.language ? ['--language', cfg.language] : [])], {
      inherit: true,
    });
  }
  const words = JSON.parse(readFileSync(paths.transcript, 'utf8'));
  return groupWords(words);
}

export async function buildComposition({ project, paths, onStatus = () => {} }) {
  const prep = readPrep(project.name);
  const tl = timeline(project, prep.duration);
  const captions = await loadCaptions({ project, paths, prep, onStatus });

  copyFileSync(gsapFile(), join(paths.build, 'gsap.min.js'));
  const customTheme = join(paths.assets, 'theme.css');
  copyFileSync(existsSync(customTheme) ? customTheme : join(TEMPLATES_DIR, 'theme.css'), join(paths.build, 'theme.css'));
  if (!existsSync(join(paths.build, 'hyperframes.json'))) {
    writeFileSync(join(paths.build, 'hyperframes.json'), JSON.stringify({ media: { autoProxy: true } }, null, 2) + '\n');
  }

  let logo = null;
  if (project.brand?.logo) {
    const src = join(paths.dir, project.brand.logo);
    if (!existsSync(src)) throw new UserError(`Logo not found: ${src}`);
    logo = `logo${extname(src)}`;
    copyFileSync(src, join(paths.build, logo));
  }

  let musicFile = null;
  let musicDuration;
  if (project.music?.file) {
    const src = join(paths.dir, project.music.file);
    if (existsSync(src)) {
      musicFile = `music${extname(src)}`;
      copyFileSync(src, join(paths.build, musicFile));
      musicDuration = (await probe(src)).duration;
    }
  }

  // Start the graphics folder fresh so switched-off graphics disappear.
  rmSync(join(paths.build, 'compositions'), { recursive: true, force: true });
  ensureDir(join(paths.build, 'compositions'));
  const files = compositionFiles({ project, tl, captions, logo, musicFile, musicDuration });
  for (const [name, html] of Object.entries(files)) writeFileSync(join(paths.build, name), html);
  return { tl, captions: captions.length };
}
